"""Alembic migrations against a real PostgreSQL (pgvector image)."""

from collections.abc import Iterator

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from testcontainers.community.postgres import PostgresContainer

from opspilot_api.db.migrations import alembic_config

pytestmark = pytest.mark.integration

TABLES = {"organizations", "users", "roles", "user_roles", "audit_logs", "services"}


@pytest.fixture(scope="module")
def database_url() -> Iterator[str]:
    with PostgresContainer("pgvector/pgvector:0.8.0-pg17", driver="psycopg") as container:
        yield container.get_connection_url()


@pytest.fixture
def config(database_url: str) -> Iterator[Config]:
    cfg = alembic_config(database_url)
    command.upgrade(cfg, "head")
    yield cfg
    command.downgrade(cfg, "base")


@pytest.fixture
def engine(database_url: str, config: Config) -> Iterator[sa.Engine]:
    eng = sa.create_engine(database_url)
    yield eng
    eng.dispose()


def _tables(eng: sa.Engine) -> set[str]:
    return set(sa.inspect(eng).get_table_names())


def test_upgrade_creates_all_tables(engine: sa.Engine) -> None:
    assert _tables(engine) >= TABLES


def test_downgrade_removes_everything(database_url: str, config: Config) -> None:
    command.downgrade(config, "base")
    eng = sa.create_engine(database_url)
    try:
        assert _tables(eng) & TABLES == set()
    finally:
        eng.dispose()
    command.upgrade(config, "head")


def test_models_match_migrations(config: Config) -> None:
    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"models and migrations differ: {exc}")


def test_initial_roles_are_seeded(engine: sa.Engine) -> None:
    with engine.connect() as conn:
        names = set(conn.execute(sa.text("SELECT name FROM roles")).scalars())
    assert names == {"viewer", "operator", "incident-commander", "administrator"}


def _insert_audit_row(conn: sa.Connection) -> None:
    org_id = conn.execute(
        sa.text("INSERT INTO organizations (name, slug) VALUES ('Acme', 'acme') RETURNING id")
    ).scalar_one()
    conn.execute(
        sa.text(
            "INSERT INTO audit_logs (organization_id, actor_type, actor_id, action, resource_type)"
            " VALUES (:org, 'user', 'u-1', 'incident.created', 'incident')"
        ),
        {"org": org_id},
    )


def test_audit_logs_reject_update(engine: sa.Engine) -> None:
    with engine.begin() as conn:
        _insert_audit_row(conn)
    with pytest.raises(sa.exc.DBAPIError, match="append-only"), engine.begin() as conn:
        conn.execute(sa.text("UPDATE audit_logs SET action = 'tampered'"))


def test_audit_logs_reject_delete(engine: sa.Engine) -> None:
    with engine.begin() as conn:
        _insert_audit_row(conn)
    with pytest.raises(sa.exc.DBAPIError, match="append-only"), engine.begin() as conn:
        conn.execute(sa.text("DELETE FROM audit_logs"))


def test_user_external_auth_id_is_unique_per_issuer(engine: sa.Engine) -> None:
    insert_user = sa.text(
        "INSERT INTO users (organization_id, issuer, external_auth_id, email, display_name)"
        " VALUES (:org, 'https://idp', 'sub-1', 'a@acme.example', 'A')"
    )
    with engine.begin() as conn:
        org_id = conn.execute(
            sa.text("INSERT INTO organizations (name, slug) VALUES ('Acme', 'acme') RETURNING id")
        ).scalar_one()
        conn.execute(insert_user, {"org": org_id})
    with pytest.raises(sa.exc.IntegrityError), engine.begin() as conn:
        conn.execute(insert_user, {"org": org_id})


def test_organization_slug_is_unique(engine: sa.Engine) -> None:
    insert = sa.text("INSERT INTO organizations (name, slug) VALUES ('Acme', 'acme')")
    with engine.begin() as conn:
        conn.execute(insert)
    with pytest.raises(sa.exc.IntegrityError), engine.begin() as conn:
        conn.execute(insert)
